import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {verifyReaderDocuments, readerPlan, inspectReaderRoot} from '../src/v10/reader_discovery.mjs';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../../..');
const EX=path.join(ROOT,'profiles/reader-discovery/examples/demo-kristal');
const load=(rel)=>JSON.parse(fs.readFileSync(path.join(EX,rel),'utf8'));
const d=load('kristal.discovery.json'),i=load('derived/reader-inventory.json'),r=load('derived/reader-profile.json');
const copy=(x)=>JSON.parse(JSON.stringify(x));
let passed=0, failed=0;
function check(label,condition){if(condition){passed++;console.log('PASS',label);}else{failed++;console.error('FAIL',label);}}
check('Kit 3.3.0 three-way metadata validates',verifyReaderDocuments(d,i,r).ok);
const basic=readerPlan(d,i,r);
check('PRF-15 causal graph specialization',basic.ok&&basic.profile==='kristal.reader/causal-graph-v1');
check('JSON and NDJSON demand different modes',basic.plan.find(x=>x.path.endsWith('diagnosis.json')).mode==='ondemand_or_dom'&&basic.plan.find(x=>x.path.endsWith('events.jsonl')).mode==='document_stream_requires_record_bound');
check('all strategies advisory; never execution or access grants',basic.plan.every(x=>!x.execution_ready&&x.authorization_required)&&basic.advisory_only);
const x=copy(d);x.reader.profile='kristal.reader/unknown-plugin-v1';
const y=copy(r);y.specialization=x.reader.profile;
check('unknown profile safely falls back to generic',readerPlan(x,i,y).profile==='kristal.reader/generic-v1');
const bad=copy(i);bad.files[0].path='../escape';
check('path traversal in inventory rejected',!verifyReaderDocuments(d,bad,r).ok);
const mismatch=copy(r);mismatch.artifact_strategies[0].size_bytes_measured+=1;
check('strategy size mismatch rejected',!verifyReaderDocuments(d,i,mismatch).ok);
const fingerprint=copy(d);fingerprint.source_fingerprint='sha256:'+'0'.repeat(64);
check('cross-document stale fingerprint rejected',!verifyReaderDocuments(fingerprint,i,r).ok);
const aggregate=copy(i);aggregate.storage.tracked_local_bytes=5;
check('inconsistent inventory counts rejected',!verifyReaderDocuments(d,aggregate,r).ok);
check('checked fixture files verify', (await inspectReaderRoot(EX,{verifyFiles:true})).ok);
const tmp=fs.mkdtempSync(path.join(os.tmpdir(),'framework-reader-'));
try{
 fs.cpSync(EX,tmp,{recursive:true});
 fs.appendFileSync(path.join(tmp,'canon/domain/diagnosis.json'),' ');
 const tampered=await inspectReaderRoot(tmp,{verifyFiles:true});
 check('byte tampering rejected',!tampered.ok&&tampered.issues.some(z=>z.code==='SIZE_MISMATCH'||z.code==='DIGEST_MISMATCH'));
 fs.copyFileSync(path.join(EX,'canon/domain/diagnosis.json'),path.join(tmp,'canon/domain/diagnosis.json'));
 fs.rmSync(path.join(tmp,'canon/domain/events.jsonl'));
 fs.symlinkSync(path.join(EX,'canon/domain/events.jsonl'),path.join(tmp,'canon/domain/events.jsonl'));
 const linked=await inspectReaderRoot(tmp,{verifyFiles:true});
 check('symlink registered payload rejected',!linked.ok&&linked.issues.some(z=>z.code==='READ_ERROR'));
 fs.rmSync(path.join(tmp,'canon/domain/events.jsonl'));
 fs.copyFileSync(path.join(EX,'canon/domain/events.jsonl'),path.join(tmp,'canon/domain/events.jsonl'));
 fs.rmSync(path.join(tmp,'derived/reader-profile.json'));
 check('partial discovery fails closed',!(await inspectReaderRoot(tmp)).ok);
}finally{fs.rmSync(tmp,{recursive:true,force:true});}
const simulated=copy(r);simulated.artifact_strategies[0].encrypted_declared=true;
const encrypted=readerPlan(d,i,simulated);
check('declared encryption must not go directly to JSON parser',encrypted.plan[0].mode==='decrypt_with_authorized_adapter_first'&&encrypted.plan[0].parser_candidate===null);
const compressed=copy(r);compressed.artifact_strategies[0].compression_declared='zstd';
check('declared compression requires bounded decompression',readerPlan(d,i,compressed).plan[0].mode==='decompress_with_bounded_adapter_first');
console.log(`Reader discovery tests: ${passed} passed, ${failed} failed`);
if(failed)process.exit(1);
